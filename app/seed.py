"""
Creates the tables and fills them with FAKE students and marks.

No real student data is ever used. Every name and mark is randomly
generated by the Faker library.

Usage:
    python seed.py                 # create 5000 students (wipes old data)
    python seed.py --count 200     # fewer students, quicker
    python seed.py --if-empty      # only seed if the database is empty

Login for every fake student:
    roll number  = e.g. 1024030001
    password     = the same roll number (test data only!)

On AWS, every new server runs `seed.py --if-empty --nowait` when it boots.
A database lock makes sure only ONE server does the seeding; the others
see the lock is taken and skip straight to starting the website.
"""
import argparse
import random
import sys
import time

from faker import Faker
from sqlalchemy import delete, func, insert, select, text
from werkzeug.security import generate_password_hash

from db import engine, grade_for, metadata, results, settings, students

FIRST_ROLL = 1024030001
BRANCH = "Computer Science and Engineering"
SEMESTER = 5

# Fictional subjects for a 3rd-year CSE term: (code, name, credits)
SUBJECTS = [
    ("CS301", "Cloud Computing", 4),
    ("CS303", "Computer Networks", 4),
    ("CS305", "Machine Learning", 4),
    ("CS307", "Compiler Design", 3),
    ("CS309", "Software Engineering", 3),
    ("HS301", "Engineering Economics", 3),
]

# 10,000 rounds of PBKDF2: realistic, but fast enough to seed 5,000 users.
HASH_METHOD = "pbkdf2:sha256:10000"


def acquire_lock(conn, wait: bool) -> bool:
    """Only one server may seed at a time (MySQL only; SQLite is local)."""
    if conn.dialect.name != "mysql":
        return True
    timeout = 600 if wait else 0
    got = conn.execute(text("SELECT GET_LOCK('portal_seed', :t)"), {"t": timeout}).scalar()
    return got == 1


def seed(count: int, if_empty: bool, wait: bool) -> None:
    fake = Faker("en_IN")
    Faker.seed(42)       # same "random" students every time -> repeatable experiments
    random.seed(42)

    with engine.connect() as conn:
        if not acquire_lock(conn, wait):
            print("Another server is seeding the database; skipping.")
            return

        metadata.create_all(conn)
        conn.commit()

        existing = conn.execute(select(func.count()).select_from(students)).scalar()
        if if_empty and existing:
            print(f"Database already has {existing} students; nothing to do.")
            return

        print(f"Creating {count} fake students...")
        started = time.time()
        conn.execute(delete(results))
        conn.execute(delete(students))
        conn.execute(delete(settings))

        student_rows, result_rows = [], []
        for i in range(count):
            roll = FIRST_ROLL + i
            ability = random.gauss(68, 12)        # each student has an "ability" level
            student_rows.append({
                "roll_no": roll,
                "name": fake.name(),
                "branch": BRANCH,
                "semester": SEMESTER,
                "password_hash": generate_password_hash(str(roll), method=HASH_METHOD),
            })
            for code, subject, credits in SUBJECTS:
                marks = int(max(18, min(99, random.gauss(ability, 9))))
                result_rows.append({
                    "roll_no": roll, "code": code, "subject": subject,
                    "credits": credits, "marks": marks, "grade": grade_for(marks),
                })

            if len(student_rows) == 500:          # insert in batches
                conn.execute(insert(students), student_rows)
                conn.execute(insert(results), result_rows)
                student_rows, result_rows = [], []
                print(f"  {i + 1} / {count}")

        if student_rows:
            conn.execute(insert(students), student_rows)
            conn.execute(insert(results), result_rows)

        # Results start UNPUBLISHED. The admin publishes them from /admin.
        conn.execute(insert(settings), [
            {"name": "published", "value": "0"},
            {"name": "published_at", "value": ""},
            {"name": "term", "value": "July–December 2026"},
        ])
        conn.commit()
        print(f"Done in {time.time() - started:.1f}s. Try roll {FIRST_ROLL} / password {FIRST_ROLL}.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--count", type=int, default=5000)
    parser.add_argument("--if-empty", action="store_true", help="skip if students already exist")
    parser.add_argument("--nowait", action="store_true", help="skip if another server is already seeding")
    parser.add_argument("--publish", action="store_true", help="publish results right away (handy locally)")
    args = parser.parse_args()
    try:
        seed(args.count, args.if_empty, wait=not args.nowait)
        if args.publish:
            with engine.begin() as conn:
                conn.execute(settings.update().where(settings.c.name == "published").values(value="1"))
            print("Results published.")
    except Exception as exc:  # noqa: BLE001
        print(f"Seeding failed: {exc}", file=sys.stderr)
        sys.exit(1)
